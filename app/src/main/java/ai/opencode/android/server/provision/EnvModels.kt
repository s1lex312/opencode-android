package ai.opencode.android.server.provision

import ai.opencode.android.data.remote.long
import ai.opencode.android.data.remote.parseJsonObjectOrNull
import ai.opencode.android.data.remote.str
import kotlinx.serialization.json.buildJsonObject
import kotlinx.serialization.json.put
import java.io.File

/**
 * Manifest of the "opencode environment" bundle.
 *
 * The bundle is a gzipped tar with this layout:
 *
 * ```
 * proot                          static arm64 proot binary
 * rootfs/                        minimal root filesystem (Ubuntu/Debian arm64)
 * rootfs/usr/local/bin/opencode  standalone opencode server binary
 * ```
 *
 * The manifest is shipped in `assets/local-env.json`, can be overridden from Settings, and is
 * generated by `server/scripts/build-rootfs.sh`.
 *
 * Parsing uses the same lenient JSON helpers as the HTTP layer, so unknown/extra fields never
 * break an install.
 */
data class EnvManifest(
    val version: String = "0",
    val abi: String = "arm64-v8a",
    /** Download URL. Empty means "read the bundle from APK assets". */
    val url: String = "",
    /** Asset file name used when [url] is blank. */
    val asset: String = DEFAULT_ASSET,
    /** Lower-case hex, or empty when the bundle is trusted because it ships inside the APK. */
    val sha256: String = "",
    val sizeBytes: Long = 0,
    val notes: String = "",
) {
    val isDownload: Boolean get() = url.isNotBlank()

    fun requireHash(): String? = sha256.trim().lowercase().takeIf { it.isNotEmpty() }

    companion object {
        const val DEFAULT_ASSET = "local-env.tar.gz"

        fun parse(text: String): EnvManifest? {
            val obj = parseJsonObjectOrNull(text) ?: return null
            return EnvManifest(
                version = obj.str("version") ?: "0",
                abi = obj.str("abi") ?: "arm64-v8a",
                url = obj.str("url").orEmpty(),
                asset = obj.str("asset") ?: DEFAULT_ASSET,
                sha256 = obj.str("sha256").orEmpty(),
                sizeBytes = obj.long("sizeBytes") ?: obj.long("size_bytes") ?: 0L,
                notes = obj.str("notes").orEmpty(),
            )
        }

        fun parseOrNull(text: String?): EnvManifest? = text?.let { runCatching { parse(it) }.getOrNull() }

        fun encode(manifest: EnvManifest): String = buildJsonObject {
            put("version", manifest.version)
            put("abi", manifest.abi)
            put("url", manifest.url)
            put("asset", manifest.asset)
            put("sha256", manifest.sha256)
            put("sizeBytes", manifest.sizeBytes)
            put("notes", manifest.notes)
        }.toString()
    }
}

/**
 * Absolute locations inside the app's private storage. Nothing here needs root.
 *
 * [nativeLibDir] is `applicationInfo.nativeLibraryDir` — the only directory Android (10+) lets an
 * app execute a binary from. Anything *written* here must be refused: the directory belongs to the
 * package installer and is mounted read-only at runtime.
 */
data class EnvPaths(val root: File, val nativeLibDir: File? = null) {

    val rootfsDir: File get() = File(root, "rootfs")
    val prootFile: File get() = File(root, "proot/proot")
    /** Scratch space proot needs for its loader (`PROOT_TMP_DIR`). */
    val tmpDir: File get() = File(root, "tmp")
    val manifestFile: File get() = File(root, "installed.json")
    val logDir: File get() = File(root, "logs")
    val logFile: File get() = File(logDir, "server.log")
    val stagingDir: File get() = File(root, ".staging")
    val downloadDir: File get() = File(root, ".download")

    /** `libproot.so` shipped in the APK — the only copy we are allowed to exec. */
    val nativeProot: File? get() = nativeLibDir?.let { File(it, "libproot.so") }?.takeIf { it.isFile }

    /** Optional `libproot_loader.so`; proot execs its loader, so it must be executable too. */
    val nativeProotLoader: File? get() = nativeLibDir?.let { File(it, "libproot_loader.so") }?.takeIf { it.isFile }

    /** Executable proot: the packaged one first (Android 10+), the extracted copy as a fallback. */
    val prootBinary: File? get() = nativeProot ?: prootFile.takeIf { it.isFile }

    /** Where proot may find shared libraries (bionic builds are dynamically linked). */
    fun prootLibraryDirs(): List<File> = listOfNotNull(
        nativeLibDir?.takeIf { nativeProot != null },
        File(root, "proot/lib").takeIf { it.isDirectory },
    )

    /** True when [target] would land in the installer-managed native library directory. */
    fun isNativeLibraryPath(target: File): Boolean {
        val dir = nativeLibDir?.canonicalPath ?: return false
        val path = runCatching { target.canonicalPath }.getOrDefault(target.absolutePath)
        return path == dir || path.startsWith(dir + File.separator)
    }

    fun prepare() {
        root.mkdirs()
        logDir.mkdirs()
    }

    fun totalSizeBytes(): Long {
        val rootfs = rootfsDir.walkTopDown().filter { it.isFile }.sumOf { it.length() }
        val proot = if (prootFile.isFile) prootFile.length() else 0L
        return rootfs + proot
    }
}

/** Coarse progress of the (only) long-running installation flow. */
data class ProvisionState(
    val phase: Phase = Phase.NOT_INSTALLED,
    val progress: Float = 0f,
    val bytesDone: Long = 0,
    val bytesTotal: Long = 0,
    val message: String? = null,
    val error: String? = null,
    val version: String? = null,
) {
    enum class Phase { NOT_INSTALLED, CHECKING, DOWNLOADING, VERIFYING, EXTRACTING, INSTALLING, READY, FAILED }

    val busy: Boolean
        get() = phase in BUSY_PHASES

    val installed: Boolean get() = phase == Phase.READY

    private companion object {
        val BUSY_PHASES = setOf(
            Phase.CHECKING,
            Phase.DOWNLOADING,
            Phase.VERIFYING,
            Phase.EXTRACTING,
            Phase.INSTALLING,
        )
    }
}

sealed interface ProvisionResult {
    data class Ok(val version: String) : ProvisionResult

    data class Err(val message: String) : ProvisionResult
}
